import { SITE_ORIGIN, PRIMARY_SITE } from './discover.mjs';

/**
 * Named explicitly rather than relying on the wildcard, so the policy is
 * legible to a human reading the file and survives a future wildcard change.
 */
export const AI_CRAWLERS = [
  'GPTBot', 'OAI-SearchBot', 'ChatGPT-User',
  'ClaudeBot', 'Claude-User', 'Claude-SearchBot',
  'PerplexityBot', 'Perplexity-User',
  'Google-Extended', 'Applebot-Extended',
  'CCBot', 'meta-externalagent',
];

export function xmlEscape(s) {
  return String(s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

export function isoDate(value) {
  return new Date(value).toISOString().slice(0, 10);
}

export function renderRobots() {
  const blocks = [
    `# robots.txt for ${SITE_ORIGIN}`,
    '# This file governs the entire origin, including every project site',
    '# published under it. Per-project robots.txt files are ignored by crawlers.',
    '# Generated by scripts/lib/render-seo.mjs — do not edit by hand.',
    '',
    'User-agent: *',
    'Allow: /',
    '',
    ...AI_CRAWLERS.flatMap((bot) => [`User-agent: ${bot}`, 'Allow: /', '']),
    `Sitemap: ${SITE_ORIGIN}/sitemap.xml`,
    '',
  ];
  return blocks.join('\n');
}

export function renderSitemapIndex(projects, now) {
  const entries = [
    { loc: `${SITE_ORIGIN}/sitemap-pages.xml`, lastmod: isoDate(now) },
    ...projects
      .filter((p) => p.hasSitemap)
      .map((p) => ({ loc: `${p.url}sitemap.xml`, lastmod: isoDate(p.updatedAt) })),
  ];
  const body = entries
    .map(({ loc, lastmod }) =>
      `  <sitemap>\n    <loc>${xmlEscape(loc)}</loc>\n    <lastmod>${lastmod}</lastmod>\n  </sitemap>`)
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</sitemapindex>
`;
}

export function renderSitemapPages(projects, now) {
  const entries = [
    { loc: `${SITE_ORIGIN}/`, lastmod: isoDate(now), priority: '1.0' },
    // Projects with their own sitemap are reached through the index instead.
    ...projects
      .filter((p) => !p.hasSitemap)
      .map((p) => ({ loc: p.url, lastmod: isoDate(p.updatedAt), priority: '0.8' })),
  ];
  const body = entries
    .map(({ loc, lastmod, priority }) =>
      `  <url>\n    <loc>${xmlEscape(loc)}</loc>\n    <lastmod>${lastmod}</lastmod>\n    <priority>${priority}</priority>\n  </url>`)
    .join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;
}

function summary(owner) {
  return `Documentation and project sites published by ${owner.name} under ${SITE_ORIGIN}. `
    + `The author's primary site, with articles and writing, is ${PRIMARY_SITE}`;
}

export function renderLlms(owner, projects) {
  const items = projects.map((p) => {
    const desc = p.description || 'No description provided.';
    const nested = p.hasLlms ? ` — [llms.txt](${p.url}llms.txt)` : '';
    return `- [${p.name}](${p.url}): ${desc}${nested}`;
  });
  return [
    `# ${owner.name} — open-source projects`,
    '',
    `> ${summary(owner)}`,
    '',
    '## Project sites',
    '',
    ...items,
    '',
    '## Elsewhere',
    '',
    `- [${new URL(PRIMARY_SITE).host}](${PRIMARY_SITE}): Primary site — articles and writing.`,
    `- [GitHub profile](${owner.htmlUrl}): Source repositories for every project listed above.`,
    `- [Full inventory](${SITE_ORIGIN}/llms-full.txt): The same list with per-project metadata.`,
    `- [projects.json](${SITE_ORIGIN}/projects.json): The same list as JSON.`,
    `- [releases.xml](${SITE_ORIGIN}/releases.xml): An Atom feed of the latest releases of all projects.`,
    '',
  ].join('\n');
}

export function renderLlmsFull(owner, projects) {
  const sections = projects.map((p) => [
    `### ${p.name}`,
    '',
    `- Site: ${p.url}`,
    `- Source: ${p.repoUrl}`,
    `- Description: ${p.description || 'No description provided.'}`,
    `- Language: ${p.language ?? 'n/a'}`,
    `- Topics: ${p.topics.length ? p.topics.join(', ') : 'none'}`,
    `- Stars: ${p.stars}`,
    `- Last updated: ${isoDate(p.updatedAt)}`,
    `- Own sitemap: ${p.hasSitemap ? `${p.url}sitemap.xml` : 'none'}`,
    `- Own llms.txt: ${p.hasLlms ? `${p.url}llms.txt` : 'none'}`,
    '',
  ].join('\n'));

  return [
    `# ${owner.name} — open-source projects (full inventory)`,
    '',
    `> ${summary(owner)}`,
    '',
    ...(owner.bio ? [owner.bio, ''] : []),
    '## Project sites',
    '',
    ...sections,
    '## Elsewhere',
    '',
    `- Primary site: ${PRIMARY_SITE}`,
    `- GitHub profile: ${owner.htmlUrl}`,
    ...(owner.twitter ? [`- X: https://x.com/${owner.twitter}`] : []),
    '',
  ].join('\n');
}

/**
 * The project list as JSON, for agents and for the WebMCP tools on the page.
 * Same facts as llms-full.txt, in a form a program reads without parsing prose.
 */
export function renderProjectsJson(owner, projects, now) {
  return `${JSON.stringify({
    owner: { name: owner.name, login: owner.login, url: PRIMARY_SITE, github: owner.htmlUrl },
    generated: new Date(now).toISOString(),
    projects: projects.map((p) => ({
      name: p.name,
      description: p.description || null,
      url: p.url,
      repository: p.repoUrl,
      language: p.language,
      topics: p.topics,
      stars: p.stars,
      updated: isoDate(p.updatedAt),
      llms: p.hasLlms ? `${p.url}llms.txt` : null,
      sitemap: p.hasSitemap ? `${p.url}sitemap.xml` : null,
      latestRelease: p.releases?.[0]
        ? { tag: p.releases[0].tag, url: p.releases[0].url, published: isoDate(p.releases[0].publishedAt) }
        : null,
    })),
  }, null, 2)}\n`;
}

/** The feed shows this many entries in all, newest first. */
export const FEED_ENTRIES = 30;
/** The feed shows this many entries of one project at most, so one busy project cannot fill it. */
export const FEED_PER_PROJECT = 3;
/** The feed drops a release that is older than this, measured from the newest release in the data. */
export const FEED_MAX_AGE_MONTHS = 24;
// A release note can be long. The entry keeps the start; the link leads to the rest.
const SUMMARY_CHARS = 1000;

/** Removes the Markdown marks from one line of text. The words stay. */
function plainLine(line) {
  return line
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<\/?[a-zA-Z][^>]*>/g, '')
    .replace(/^\s{0,3}(?:>\s?)+/, '')
    .replace(/^\s*(?:[-*+]|\d+[.)])\s+(?:\[[ xX]\]\s+)?/, '')
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/\[([^\]]+)\]\[[^\]]*\]/g, '$1')
    .replace(/`+/g, '')
    .replace(/(\*\*|__)(?=\S)(.+?)(?<=\S)\1/g, '$2')
    .replace(/(^|[^\w*])\*(?=\S)([^*]+?)(?<=\S)\*(?![\w*])/g, '$1$2')
    .replace(/(^|[^\w_])_(?=\S)([^_]+?)(?<=\S)_(?![\w_])/g, '$1$2')
    .replace(/~~(.+?)~~/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * The first paragraph of a release note as plain text. A heading, a rule, a code fence line and
 * an empty block are not a paragraph. The items of a list become one line with "; " between them.
 */
export function plainSummary(body) {
  const blocks = String(body ?? '').replace(/\r\n?/g, '\n').split(/\n\s*\n/);
  for (const block of blocks) {
    const lines = block.split('\n')
      .filter((l) => !/^\s{0,3}(?:#{1,6}(?:\s|$)|```|~~~|(?:[-*_]\s*){3,}$|=+\s*$)/.test(l));
    const isList = lines.length > 1 && lines.every((l) => /^\s*(?:[-*+]|\d+[.)])\s+/.test(l));
    const text = lines.map(plainLine).filter(Boolean).join(isList ? '; ' : ' ');
    if (text) return text.length > SUMMARY_CHARS ? `${text.slice(0, SUMMARY_CHARS).trimEnd()} …` : text;
  }
  return '';
}

/**
 * The entries of the feed, newest first. The rules, in this order:
 * 1. Drop a release older than FEED_MAX_AGE_MONTHS, measured from the newest release in the data.
 *    The wall clock is not an input, so the same data gives the same file.
 * 2. Releases of one project published in the same minute become one entry.
 * 3. Keep FEED_PER_PROJECT entries of each project, then FEED_ENTRIES entries in all.
 */
export function feedEntries(projects) {
  const all = projects.flatMap((p) => (p.releases ?? []).map((r) => ({ ...r, site: p.url ?? null })));
  if (all.length === 0) return [];
  const newest = new Date(all.reduce((max, r) => (r.publishedAt > max ? r.publishedAt : max), all[0].publishedAt));
  const cutoff = new Date(newest);
  cutoff.setUTCMonth(cutoff.getUTCMonth() - FEED_MAX_AGE_MONTHS);
  const groups = new Map();
  for (const r of all) {
    if (new Date(r.publishedAt) < cutoff) continue;
    const key = `${r.project}\n${r.publishedAt.slice(0, 16)}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(r);
  }
  const perProject = new Map();
  return [...groups.values()]
    .map((list) => {
      const releases = list.toSorted((a, b) => b.publishedAt.localeCompare(a.publishedAt) || a.tag.localeCompare(b.tag));
      const [first] = releases;
      return {
        project: first.project,
        site: first.site,
        url: first.url,
        publishedAt: first.publishedAt,
        tags: releases.map((r) => r.tag),
        summary: releases.map((r) => plainSummary(r.body)).find(Boolean) ?? '',
      };
    })
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt) || a.project.localeCompare(b.project))
    .filter((e) => {
      const n = (perProject.get(e.project) ?? 0) + 1;
      perProject.set(e.project, n);
      return n <= FEED_PER_PROJECT;
    })
    .slice(0, FEED_ENTRIES);
}

/**
 * An Atom feed of the latest releases of all projects. Its <updated> is the newest
 * release date, not the build time, so a rebuild without a new release gives the same file.
 */
export function renderReleasesAtom(owner, projects) {
  const entries = feedEntries(projects);
  const updated = entries[0]?.publishedAt ?? '1970-01-01T00:00:00Z';
  const items = entries.map((e) => [
    '  <entry>',
    `    <id>${xmlEscape(e.url)}</id>`,
    `    <title>${xmlEscape(`${e.project} ${e.tags.join(', ')}`)}</title>`,
    `    <link rel="alternate" type="text/html" href="${xmlEscape(e.url)}"/>`,
    ...(e.site ? [`    <link rel="related" type="text/html" href="${xmlEscape(e.site)}" title="${xmlEscape(`${e.project} project site`)}"/>`] : []),
    `    <updated>${xmlEscape(e.publishedAt)}</updated>`,
    `    <published>${xmlEscape(e.publishedAt)}</published>`,
    `    <category term="${xmlEscape(e.project)}"/>`,
    ...(e.summary ? [`    <summary type="text">${xmlEscape(e.summary)}</summary>`] : []),
    '  </entry>',
  ].join('\n'));
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<feed xmlns="http://www.w3.org/2005/Atom">',
    `  <id>${SITE_ORIGIN}/releases.xml</id>`,
    `  <title>${xmlEscape(`${owner.name} — open-source releases`)}</title>`,
    `  <subtitle>${xmlEscape(`This file is a release feed. It lists the new releases of the open-source projects of ${owner.name}. `
      + `Add its address to a feed reader to get each new release. It shows at most ${FEED_PER_PROJECT} entries for each project, `
      + `from the last ${FEED_MAX_AGE_MONTHS} months. The project list is at ${SITE_ORIGIN}/`)}</subtitle>`,
    `  <link rel="self" type="application/atom+xml" href="${SITE_ORIGIN}/releases.xml"/>`,
    `  <link rel="alternate" type="text/html" href="${SITE_ORIGIN}/"/>`,
    `  <updated>${xmlEscape(updated)}</updated>`,
    `  <author><name>${xmlEscape(owner.name)}</name><uri>${xmlEscape(PRIMARY_SITE)}</uri></author>`,
    ...items,
    '</feed>',
    '',
  ].join('\n');
}
